// Writes packages/shared/src/speech-models.ts: every file of the default speech model at a
// pinned revision, with size and SHA-256. Large files take the SHA-256 the host publishes
// for them; small files are downloaded and hashed here. Run again only to change the model.
//
//   node scripts/make-speech-manifest.mjs

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HOST = "https://huggingface.co";

const SOURCES = [
  {
    repo: "argmaxinc/whisperkit-coreml",
    revision: "0f63a7800b00dd0226abd051b906c246e1907482",
    folder: "openai_whisper-large-v3-v20240930_turbo_632MB",
    target: "model",
    include: () => true,
  },
  {
    repo: "openai/whisper-large-v3",
    revision: "06f233fe06e710322aca913c1bc4249a0d71fce1",
    folder: "",
    target: "tokenizer",
    include: (name) => name === "tokenizer.json" || name === "tokenizer_config.json",
  },
];

async function listFiles(source) {
  const url = `${HOST}/api/models/${source.repo}/tree/${source.revision}/${source.folder}?recursive=true`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const entries = await response.json();
  return entries.filter((entry) => entry.type === "file");
}

async function sha256Of(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return createHash("sha256")
    .update(Buffer.from(await response.arrayBuffer()))
    .digest("hex");
}

const files = [];
for (const source of SOURCES) {
  for (const entry of await listFiles(source)) {
    const relative = source.folder ? entry.path.slice(source.folder.length + 1) : entry.path;
    if (!source.include(relative)) continue;
    const url = `${HOST}/${source.repo}/resolve/${source.revision}/${entry.path}`;
    const sha256 = entry.lfs?.oid ?? (await sha256Of(url));
    files.push({ path: `${source.target}/${relative}`, url, size: entry.size, sha256 });
  }
}
files.sort((a, b) => a.path.localeCompare(b.path));

const total = files.reduce((sum, file) => sum + file.size, 0);
const body = `// Generated by scripts/make-speech-manifest.mjs. Do not edit by hand.
// This file has no imports so a plain Node script can load it.

export interface SpeechModelFile {
  /** Path inside the model's folder: \`model/...\` or \`tokenizer/...\`. */
  path: string;
  /** HTTPS address at a pinned revision. */
  url: string;
  size: number;
  sha256: string;
}

export interface SpeechModel {
  id: string;
  label: string;
  totalBytes: number;
  files: readonly SpeechModelFile[];
}

/** The default speech model (vault ADR-0013, owner's choice in Session 03). */
export const DEFAULT_SPEECH_MODEL: SpeechModel = ${JSON.stringify(
  {
    id: "whisper-large-v3-turbo-632mb",
    label: "Whisper large-v3 turbo (compressed)",
    totalBytes: total,
    files,
  },
  null,
  2,
)};
`;

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "../packages/shared/src/speech-models.ts");
await writeFile(out, body);
console.log(`wrote ${files.length} files, ${(total / 1e6).toFixed(0)} MB, to ${out}`);

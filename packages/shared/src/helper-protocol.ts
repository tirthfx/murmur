/**
 * Helper protocol: the envelope and the handshake, liveness and error messages.
 * Names and shapes follow the vault note "Helper Protocol". Receivers ignore unknown
 * payload fields (plain `z.object` strips them); the envelope itself is strict.
 */

/** Longest accepted line in bytes, terminator excluded (1 MiB). */
export const MAX_LINE_BYTES = 1_048_576;

// ---------------------------------------------------------------- error codes

export const HELPER_ERROR_CODES = [
  "HANDSHAKE_REQUIRED",
  "PROTOCOL_VERSION_MISMATCH",
  "UNSUPPORTED_REQUEST",
  "INVALID_PAYLOAD",
  "NOT_FOUND",
  "BUSY",
  "PERMISSION_DENIED",
  "DEVICE_NOT_FOUND",
  "DEVICE_UNAVAILABLE",
  "AUDIO_ENGINE_FAILED",
  "MODEL_NOT_LOADED",
  "MODEL_LOAD_FAILED",
  "TRANSCRIPTION_FAILED",
  "TRANSCRIPTION_TIMEOUT",
  "CONTEXT_UNAVAILABLE",
  "PASTE_FAILED",
  "PASTE_BLOCKED",
  "CLIPBOARD_RESTORE_FAILED",
  "SCREEN_CAPTURE_FAILED",
  "CONFLICT",
  "KEYCHAIN_FAILED",
  "INTERNAL",
] as const;

/** Codes generated by main, never sent by the helper. */
export const MAIN_ERROR_CODES = [
  "HELPER_RESTARTED",
  "HELPER_TIMEOUT",
  "HELPER_UNAVAILABLE",
] as const;

export type HelperErrorCode =
  (typeof HELPER_ERROR_CODES)[number] | (typeof MAIN_ERROR_CODES)[number];

const helperErrorCodeSchema = z.enum(HELPER_ERROR_CODES);

// ------------------------------------------------------------------- envelope

/** `{id, type, payload}`. The id is null for events. */
export const envelopeSchema = z.strictObject({
  id: z.string().nullable(),
  type: z.string().min(1),
  payload: z.record(z.string(), z.unknown()),
});

export type Envelope = z.infer<typeof envelopeSchema>;

/** Request ids are `m-` plus a counter zero-padded to six digits. */
export function formatRequestId(counter: number): string {
  return `m-${String(counter).padStart(6, "0")}`;
}

// ------------------------------------------------------------------- payloads

export const helloPayloadSchema = z.object({
  protocolVersion: z.number().int(),
  helperVersion: z.string().min(1),
  capabilities: z.array(z.string()),
  pid: z.number().int().optional(),
});
export type HelloPayload = z.infer<typeof helloPayloadSchema>;

export const helloAckPayloadSchema = z.object({
  accepted: z.boolean(),
  protocolVersion: z.number().int(),
  appVersion: z.string(),
  reason: z.string().optional(),
});
export type HelloAckPayload = z.infer<typeof helloAckPayloadSchema>;

const emptyObjectSchema = z.object({});

export const shutdownPayloadSchema = z.object({ reason: z.string() });

export const permissionsRequestPayloadSchema = z.object({ kind: permissionKindSchema });

/** Request name to payload and result schemas. */
export const HELPER_REQUESTS = {
  "hello.ack": {
    payload: helloAckPayloadSchema,
    result: z.object({ ready: z.boolean() }),
  },
  ping: {
    payload: emptyObjectSchema,
    result: z.object({ uptimeMs: z.number().nonnegative() }),
  },
  shutdown: {
    payload: shutdownPayloadSchema,
    result: emptyObjectSchema,
  },
  "permissions.status": {
    payload: emptyObjectSchema,
    result: permissionSnapshotSchema,
  },
  "permissions.request": {
    payload: permissionsRequestPayloadSchema,
    result: permissionRequestResultSchema,
  },
  "hotkey.configure": {
    payload: hotkeyConfigurePayloadSchema,
    result: hotkeyConfigureResultSchema,
  },
  "audio.start": {
    payload: audioStartPayloadSchema,
    result: audioStartResultSchema,
  },
  "audio.stop": {
    payload: audioSessionPayloadSchema,
    result: audioStopResultSchema,
  },
  "audio.cancel": {
    payload: audioSessionPayloadSchema,
    result: audioCancelResultSchema,
  },
  "transcribe.load": {
    payload: transcribeLoadPayloadSchema,
    result: transcribeLoadResultSchema,
  },
  "transcribe.unload": {
    payload: emptyObjectSchema,
    result: emptyObjectSchema,
  },
  "transcribe.file": {
    payload: transcribeFilePayloadSchema,
    result: transcriptSchema,
  },
  "insert.text": {
    payload: insertTextPayloadSchema,
    result: insertTextResultSchema,
  },
  "insert.copy": {
    payload: insertCopyPayloadSchema,
    result: emptyObjectSchema,
  },
} as const;

export type HelperRequestType = keyof typeof HELPER_REQUESTS;
export type HelperRequestPayload<K extends HelperRequestType> = z.infer<
  (typeof HELPER_REQUESTS)[K]["payload"]
>;
export type HelperRequestResult<K extends HelperRequestType> = z.infer<
  (typeof HELPER_REQUESTS)[K]["result"]
>;

export const helperErrorEventPayloadSchema = z.object({
  code: helperErrorCodeSchema,
  message: z.string(),
  fatal: z.boolean(),
});
export type HelperErrorEventPayload = z.infer<typeof helperErrorEventPayloadSchema>;

/**
 * Feature events main dispatches to subscribers, by type. `hello` and `helper.error` are
 * handled by the connection itself and are not listed here.
 */
export const HELPER_EVENTS = {
  "hotkey.event": hotkeyEventPayloadSchema,
  "hotkey.tap.status": hotkeyTapStatusPayloadSchema,
  "audio.level": audioLevelPayloadSchema,
  "audio.silent": audioSilentPayloadSchema,
} as const;

export type HelperEventType = keyof typeof HELPER_EVENTS;
export type HelperEventMessage = {
  [K in HelperEventType]: { type: K; payload: z.infer<(typeof HELPER_EVENTS)[K]> };
}[HelperEventType];

export function isHelperEventType(type: string): type is HelperEventType {
  return Object.hasOwn(HELPER_EVENTS, type);
}

// ------------------------------------------------------------------- response

export const responseErrorSchema = z.object({
  code: z.string().min(1),
  message: z.string(),
  retryable: z.boolean(),
});
export type ResponseError = z.infer<typeof responseErrorSchema>;

/** Payload of a `response` message. `result` is checked per request by the caller. */
export const responsePayloadSchema = z.discriminatedUnion("ok", [
  z.object({
    requestType: z.string(),
    ok: z.literal(true),
    result: z.record(z.string(), z.unknown()),
  }),
  z.object({
    requestType: z.string(),
    ok: z.literal(false),
    error: responseErrorSchema,
  }),
]);
export type ResponsePayload = z.infer<typeof responsePayloadSchema>;

// ------------------------------------------------------- whole-message schemas

const eventEnvelope = <T extends string, P extends z.ZodType>(type: T, payload: P) =>
  z.strictObject({ id: z.null(), type: z.literal(type), payload });

const requestEnvelope = <T extends string, P extends z.ZodType>(type: T, payload: P) =>
  z.strictObject({ id: z.string(), type: z.literal(type), payload });

export const helloEventSchema = eventEnvelope("hello", helloPayloadSchema);
export const helperErrorEventSchema = eventEnvelope("helper.error", helperErrorEventPayloadSchema);
export const responseSchema = z.strictObject({
  id: z.string(),
  type: z.literal("response"),
  payload: responsePayloadSchema,
});

export const helloAckRequestSchema = requestEnvelope("hello.ack", helloAckPayloadSchema);
export const pingRequestSchema = requestEnvelope("ping", HELPER_REQUESTS.ping.payload);
export const shutdownRequestSchema = requestEnvelope("shutdown", shutdownPayloadSchema);
export const permissionsStatusRequestSchema = requestEnvelope(
  "permissions.status",
  HELPER_REQUESTS["permissions.status"].payload,
);
export const permissionsRequestRequestSchema = requestEnvelope(
  "permissions.request",
  permissionsRequestPayloadSchema,
);
export const hotkeyConfigureRequestSchema = requestEnvelope(
  "hotkey.configure",
  hotkeyConfigurePayloadSchema,
);
export const hotkeyEventSchema = eventEnvelope("hotkey.event", hotkeyEventPayloadSchema);
export const hotkeyTapStatusEventSchema = eventEnvelope(
  "hotkey.tap.status",
  hotkeyTapStatusPayloadSchema,
);

export const audioStartRequestSchema = requestEnvelope("audio.start", audioStartPayloadSchema);
export const audioStopRequestSchema = requestEnvelope("audio.stop", audioSessionPayloadSchema);
export const audioCancelRequestSchema = requestEnvelope("audio.cancel", audioSessionPayloadSchema);
export const audioLevelEventSchema = eventEnvelope("audio.level", audioLevelPayloadSchema);
export const audioSilentEventSchema = eventEnvelope("audio.silent", audioSilentPayloadSchema);

export const transcribeLoadRequestSchema = requestEnvelope(
  "transcribe.load",
  transcribeLoadPayloadSchema,
);
export const transcribeUnloadRequestSchema = requestEnvelope(
  "transcribe.unload",
  emptyObjectSchema,
);
export const transcribeFileRequestSchema = requestEnvelope(
  "transcribe.file",
  transcribeFilePayloadSchema,
);

export const insertTextRequestSchema = requestEnvelope("insert.text", insertTextPayloadSchema);
export const insertCopyRequestSchema = requestEnvelope("insert.copy", insertCopyPayloadSchema);

export type HelloEvent = z.infer<typeof helloEventSchema>;
export type HelperResponse = z.infer<typeof responseSchema>;

/** Helper-to-main messages main understands in this protocol version. */
export type HelperEvent = HelloEvent | z.infer<typeof helperErrorEventSchema>;

import { readFileSync, readdirSync } from "node:fs";
import { PLAN_FEATURES, featureTier } from "../../../packages/shared/src/plans.ts";

/**
 * The two matrices the database holds as data, written as SQL from their sources: the permission
 * matrix in `services/local-server/src/permissions.json` and the plan matrix in
 * `packages/shared/src/plans.ts`. `migrations/..._seed_matrices.sql` is exactly this output, and
 * a test compares the two, so the server and the database cannot drift (SW-04).
 */
interface PermissionsFile {
  roles: string[];
  actions: Record<
    string,
    { scope: "server" | "team"; roles: string[]; departmentScoped?: string[] }
  >;
}

const PERMISSIONS = new URL("../../local-server/src/permissions.json", import.meta.url);

const q = (value: string) => `'${value.replaceAll("'", "''")}'`;

const MIGRATIONS = new URL("../migrations/", import.meta.url);
const SEED_NAME = /^(\d{14})_seed_matrices(?:_\d+)?\.sql$/;

/** The seed migrations so far, oldest first. A migration is never edited once applied. */
export function seedFiles(): string[] {
  return readdirSync(MIGRATIONS)
    .filter((name) => SEED_NAME.test(name))
    .sort();
}

/** The newest seed migration: the one that must say what the sources say now. */
export function latestSeed(): { name: string; sql: string } {
  const name = seedFiles().at(-1);
  if (!name) throw new Error("There is no seed migration.");
  return { name, sql: readFileSync(new URL(name, MIGRATIONS), "utf8") };
}

/** Only the statements: no comments, and no `delete`, so a first seed and a replacement compare. */
export function statementsOf(sql: string): string {
  return sql
    .replace(/--[^\n]*/g, "")
    .replace(/^\s*delete from [^;]*;\s*$/gim, "")
    .trim();
}

/** The name of the next migration, numbered after the last one. */
export function nextMigrationName(label: string): string {
  const last = readdirSync(MIGRATIONS)
    .filter((name) => name.endsWith(".sql"))
    .sort()
    .at(-1);
  const number = Number((last ?? "20261124000000").slice(0, 14)) + 1;
  return `${number}_${label}.sql`;
}

export function seedSql(replace = false): string {
  const file = JSON.parse(readFileSync(PERMISSIONS, "utf8")) as PermissionsFile;
  const permissions: string[] = [];
  for (const [action, rule] of Object.entries(file.actions))
    for (const role of rule.roles)
      permissions.push(
        `  (${q(action)}, ${q(rule.scope)}, ${q(role)}, ${rule.departmentScoped?.includes(role) ? "true" : "false"})`,
      );
  const features = PLAN_FEATURES.map((feature) => `  (${q(feature)}, ${q(featureTier(feature))})`);
  return `-- The permission matrix and the plan matrix, as data (SW-04).
--
-- GENERATED by \`npm run seed --workspace @murmur/supabase\` from
-- services/local-server/src/permissions.json and packages/shared/src/plans.ts. Do not edit by
-- hand: a test fails when this file and its sources disagree.

${
  replace
    ? "-- Replaces what an earlier seed wrote: the rows below are the whole matrix.\ndelete from public.role_permissions;\ndelete from public.plan_features;\n\n"
    : ""
}insert into public.role_permissions (action, scope, role, department_scoped) values
${permissions.join(",\n")};

insert into public.plan_features (feature, min_tier) values
${features.join(",\n")};
`;
}

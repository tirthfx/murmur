import { readFileSync } from "node:fs";
import { PLAN_FEATURES, featureTier } from "../../../packages/shared/src/plans.ts";

/**
 * The two matrices the database holds as data, written as SQL from their sources: the permission
 * matrix in `services/local-server/src/permissions.json` and the plan matrix in
 * `packages/shared/src/plans.ts`. `migrations/..._seed_matrices.sql` is exactly this output, and
 * a test compares the two, so the server and the database cannot drift (SW-04).
 */
interface PermissionsFile {
  roles: string[];
  actions: Record<
    string,
    { scope: "server" | "team"; roles: string[]; departmentScoped?: string[] }
  >;
}

const PERMISSIONS = new URL("../../local-server/src/permissions.json", import.meta.url);

const q = (value: string) => `'${value.replaceAll("'", "''")}'`;

export const SEED_FILE = new URL("../migrations/20261124000002_seed_matrices.sql", import.meta.url);

export function seedSql(): string {
  const file = JSON.parse(readFileSync(PERMISSIONS, "utf8")) as PermissionsFile;
  const permissions: string[] = [];
  for (const [action, rule] of Object.entries(file.actions))
    for (const role of rule.roles)
      permissions.push(
        `  (${q(action)}, ${q(rule.scope)}, ${q(role)}, ${rule.departmentScoped?.includes(role) ? "true" : "false"})`,
      );
  const features = PLAN_FEATURES.map((feature) => `  (${q(feature)}, ${q(featureTier(feature))})`);
  return `-- 0002 the permission matrix and the plan matrix, as data (SW-04).
--
-- GENERATED by \`npm run seed --workspace @murmur/supabase\` from
-- services/local-server/src/permissions.json and packages/shared/src/plans.ts. Do not edit by
-- hand: a test fails when this file and its sources disagree.

insert into public.role_permissions (action, scope, role, department_scoped) values
${permissions.join(",\n")};

insert into public.plan_features (feature, min_tier) values
${features.join(",\n")};
`;
}
